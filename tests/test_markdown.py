from datetime import date
from pathlib import Path

from podcleaner_editor.audio_io import AudioInfo
from podcleaner_editor.cutmap import CutMap
from podcleaner_editor.episode import Episode, Track
from podcleaner_editor.events import Event, EventType
from podcleaner_editor.report.markdown import AnalysisResult, render_edit_file
from podcleaner_editor.timeline import Interval as I

DAY = date(2026, 11, 22)


def _track(label: str, name: str, channels: int = 1) -> Track:
    return Track(label, AudioInfo(Path(name), 74.75, 44100, channels, "pcm_f32le", "wav"))


SEPARATE = Episode(
    "Episode 42",
    (_track("Julien", "julien.wav"), _track("Franck", "franck.wav")),
    _track("Film", "film.wav", channels=2),
)
MIXED = Episode("Episode 43", (_track("Julien + Franck", "voices.wav", 2),), SEPARATE.film)

FILM = Event(EventType.FILM_CLIP, 61.5, 66.5, "Film", "Activity on the film track")
OVERLAP = Event(EventType.OVERLAP, 48.0, 49.2, "Franck", "Franck tries to speak; Julien keeps it")


def _render(episode=SEPARATE, events=(), cuts=(), dry_run=True) -> str:
    result = AnalysisResult(episode, list(events), CutMap(tuple(cuts)), dry_run)
    return render_edit_file(result, "0.1.0", DAY)


def test_render_matches_expected_snippet():
    text = _render(events=[FILM, OVERLAP], cuts=[I(15.0, 17.5)])
    expected_head = (
        "# Episode 42: edit file\n"
        "\n"
        "Generated by podcleaner-editor 0.1.0 on 2026-11-22 · mode: dry run"
        " · layout: separate tracks\n"
        "\n"
        "## Timecodes\n"
        "\n"
        "| # | Type | Track | Original | Final | Duration | Reason |\n"
        "| --- | --- | --- | --- | --- | --- | --- |\n"
        "| 1 | Overlap | Franck | 00:00:48.000 | 00:00:45.500 | 00:00:01.200 |"
        " Franck tries to speak; Julien keeps it |\n"
        "| 2 | Film clip | Film | 00:01:01.500 | 00:00:59.000 | 00:00:05.000 |"
        " Activity on the film track |\n"
        "\n"
        "## Report\n"
    )
    assert text.startswith(expected_head)


def test_tracks_table():
    text = _render()
    assert "### Tracks\n\n| Track | File | Duration | Sample rate | Channels |\n" in text
    assert "| Julien | julien.wav | 00:01:14.750 | 44100 Hz | 1 |" in text
    assert "| Film | film.wav | 00:01:14.750 | 44100 Hz | 2 |" in text


def test_empty_events_line():
    text = _render()
    assert "## Timecodes\n\n_No events._\n" in text
    assert "| # |" not in text


def test_pipe_in_reason_is_escaped():
    odd = Event(EventType.OVERLAP, 1, 2, "Franck", "a | b")
    assert "| a \\| b |" in _render(events=[odd])


def test_report_counts_silences():
    text = _render(cuts=[I(10, 12), I(20, 25.5)])
    assert (
        "### Silences\n\n2 silences shortened, 00:00:07.500 removed. "
        "Final duration: 00:01:07.250 (original: 00:01:14.750).\n"
    ) in text


def test_one_silence_is_singular():
    assert "1 silence shortened, 00:00:02.000 removed." in _render(cuts=[I(10, 12)])


def test_separate_layout_counts_overlaps():
    assert "### Overlaps\n\n1 attempt to take the floor flagged.\n" in _render(events=[OVERLAP])
    assert "0 attempts to take the floor flagged." in _render()


def test_mixed_layout_says_overlaps_not_available():
    text = _render(episode=MIXED)
    assert "layout: mixed voices" in text
    assert "### Overlaps\n\nNot available: both voices are on one track.\n" in text


def test_claude_section_without_claude():
    assert _render().endswith("### Claude's opinions\n\nNone: processed without Claude.\n")


def test_edit_mode():
    assert "· mode: edit ·" in _render(dry_run=False)
