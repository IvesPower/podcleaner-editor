DAY = date(2026, 11, 22)


def _track(label: str, name: str, channels: int = 1) -> Track:
    return Track(label, AudioInfo(Path(name), 74.75, 44100, channels, "pcm_f32le", "wav"))


SEPARATE = Episode(
    "Episode 42",
    (_track("Julien", "julien.wav"), _track("Franck", "franck.wav")),
    _track("Film", "film.wav", channels=2),
)
MIXED = Episode("Episode 43", (_track("Julien + Franck", "voices.wav", 2),), SEPARATE.film)

FILM = Event(EventType.FILM_CLIP, 61.5, 66.5, "Film", "Activity on the film track")
OVERLAP = Event(EventType.OVERLAP, 48.0, 49.2, "Franck", "Franck tries to speak; Julien keeps it")


def _render(episode=SEPARATE, events=(), cuts=(), dry_run=True) -> str:
    result = AnalysisResult(episode, list(events), CutMap(tuple(cuts)), dry_run)
    return render_edit_file(result, "0.1.0", DAY)


def test_render_matches_expected_snippet():
    text = _render(events=[FILM, OVERLAP], cuts=[I(15.0, 17.5)])
    expected_head = (
        "# Episode 42: edit file\n"
        "\n"
        "Generated by podcleaner-editor 0.1.0 on 2026-11-22 · mode: dry run"
        " · layout: separate tracks\n"
        "\n"
        "## Timecodes\n"
        "\n"
        "| # | Type | Track | Original | Final | Duration | Reason |\n"
        "| --- | --- | --- | --- | --- | --- | --- |\n"
        "| 1 | Overlap | Franck | 00:00:48.000 | 00:00:45.500 | 00:00:01.200 |"
        " Franck tries to speak; Julien keeps it |\n"
        "| 2 | Film clip | Film | 00:01:01.500 | 00:00:59.000 | 00:00:05.000 |"
        " Activity on the film track |\n"
        "\n"
        "## Report\n"
    )
    assert text.startswith(expected_head)


